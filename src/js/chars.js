/* ============ chars.js — 形象登记处 ============
   一个形象 = 一张位图 + 一组尺寸/着地参数。换形象只换这三样，
   状态机、饥饿、吃图标、遗书剧情统统不用改。
      src   : 立绘（2x 图，assets/ 下）
      gap   : 盒底到"脚底"的空白，用来把她精准放在地板上
      float : 悬空高度（离地几像素）。0 = 用腿站着
      mouth : 嘴在盒子里的纵向比例，气泡和投喂都靠它对准
      mouthX: 嘴的横向比例（立绘的脸中轴略偏右，不写就是 0.5）

   尺寸推导：立绘画布 714×1423（宽高比 0.50176），取 W=120 ⇒ H=239。
   想改大小只动 w/h 两个数，比例保持 1.993 即可，图不用重新出。
   ============================================ */
(function (w) {
  const Pet = w.Pet;

  Pet.chars = {
    ram: {
      id: 'ram',
      name: '拉姆',
      w: 120,
      h: 239,
      gap: 2,
      float: 0,
      mouth: 0.442,
      mouthX: 0.536,
      src: 'assets/ram.png'
    },
    rem: {
      id: 'rem',
      name: '雷姆',
      w: 120,
      h: 239,
      gap: 2,
      float: 0,
      mouth: 0.442,
      mouthX: 0.536,
      src: 'assets/rem.png'
    }
  };

  /* 形象顺序：右键菜单按这个顺序轮换，第一项是默认 */
  Pet.charOrder = ['ram', 'rem'];
})(window);
